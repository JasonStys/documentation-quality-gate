/**
 * @file Exact source declaration map generator and freshness checker.
 * @description Parses authored TypeScript/JavaScript without executing it; lists definitions, parameters and variables.
 * @remarks Symbol locations, including this script, are generated in docs/code-map.md.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import console from 'node:console';
import { fileURLToPath } from 'node:url';
import * as ts from 'typescript';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'docs/code-map.md');

/** Lists only authored roots, without traversing symbolic directory links. */
async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collect(absolute)));
    else if (entry.isFile() && /\.[cm]?[jt]s$/u.test(entry.name)) files.push(absolute);
  }
  return files;
}

/** Flattens identifiers in destructuring bindings into precise declaration nodes. */
function bindingNames(name) {
  if (ts.isIdentifier(name)) return [name];
  if (ts.isObjectBindingPattern(name) || ts.isArrayBindingPattern(name))
    return name.elements.flatMap((element) =>
      ts.isBindingElement(element) ? bindingNames(element.name) : [],
    );
  return [name];
}

/** Parses symbol and parameter locations from syntax trees, not fragile text searches. */
function declarations(file, source) {
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const rows = [];
  function visit(node) {
    let kind;
    if (ts.isFunctionDeclaration(node)) kind = 'function';
    else if (ts.isClassDeclaration(node)) kind = 'class';
    else if (ts.isInterfaceDeclaration(node)) kind = 'interface';
    else if (ts.isTypeAliasDeclaration(node)) kind = 'type';
    else if (ts.isMethodDeclaration(node)) kind = 'method';
    else if (ts.isVariableDeclaration(node)) kind = 'variable';
    else if (ts.isParameter(node)) kind = 'parameter';
    if (kind && node.name)
      for (const name of bindingNames(node.name))
        rows.push({
          kind,
          name: name.getText(tree),
          line: tree.getLineAndCharacterOfPosition(name.getStart(tree)).line + 1,
        });
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return rows;
}

const files = (
  await Promise.all(
    ['src', 'scripts', 'tests'].map((dir) => collect(path.join(root, dir))),
  )
).flat();
const lines = [
  '# Code map and declaration locations',
  '',
  'Generated by `pnpm code-map`; checked with `pnpm code-map:check`. Lines refer to formatted source. Definitions, parameters and variables are navigation aids, not API contracts.',
  '',
  '| File | Kind | Symbol | Line |',
  '| --- | --- | --- | ---: |',
];
let count = 0;
for (const file of files) {
  const relative = path.relative(root, file).replaceAll('\\', '/');
  for (const item of declarations(file, await readFile(file, 'utf8'))) {
    const label = item.name.replaceAll('`', '').replaceAll('|', '\\|');
    lines.push(
      `| ${relative} | ${item.kind} | ${label} | [${item.line}](../${relative}#L${item.line}) |`,
    );
    count += 1;
  }
}
const generated = await format(lines.join('\n') + '\n', {
  ...(await resolveConfig(output)),
  parser: 'markdown',
});
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated)
    throw new Error('Code map is stale; run pnpm code-map.');
} else await writeFile(output, generated, 'utf8');
console.log(`Code map: ${files.length} files, ${count} exact declaration locations.`);
